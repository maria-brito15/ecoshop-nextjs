#!/usr/bin/env node
// scripts/sdd/adr-index.mjs — generates docs/architecture/adr/README.md and validates the supersession chain.
// Usage: node scripts/sdd/adr-index.mjs [--check]   (--check: fails if the index is out of date)
import { join } from "node:path";
import { existsSync, writeFileSync } from "node:fs";
import {
  ADR_DIR,
  ROOT,
  read,
  readAdrs,
  listFiles,
  report,
  statusKey,
} from "./lib.mjs";

const adrs = readAdrs().sort((a, b) => a.id.localeCompare(b.id));
const byId = new Map(adrs.map((a) => [a.id, a]));
const errors = [];

for (const a of adrs) {
  if (!statusKey(a.status)) errors.push(`${a.id}: invalid status "${a.status}"`);
  if (statusKey(a.status) === "superseded") {
    const next = byId.get(a.supersededBy ?? "");
    if (!next) errors.push(`${a.id}: "Superseded by" target does not exist`);
    else if (next.supersedes !== a.id)
      errors.push(`${next.id} should declare "Supersedes: ${a.id}"`);
  }
  if (a.supersedes) {
    const old = byId.get(a.supersedes);
    if (!old)
      errors.push(`${a.id}: "Supersedes" ${a.supersedes} does not exist`);
    else if (statusKey(old.status) !== "superseded")
      errors.push(`${old.id} should be "Superseded"`);
  }
}

// specs and plans must not cite a superseded ADR as current (on the "ADRs:" line)
const docs = [
  ...listFiles(join(ROOT, "docs/capabilities"), (p) => p.endsWith("spec.md")),
  ...listFiles(
    join(ROOT, "specs"),
    (p) => p.endsWith("plan.md") || p.endsWith("spec.md"),
  ),
];
for (const d of docs) {
  for (const l of read(d)
    .split("\n")
    .filter((x) => /ADRs?[^:]*:/i.test(x) && /ADR-\d{4}/.test(x))) {
    for (const id of l.match(/ADR-\d{4}/g)) {
      if (
        statusKey(byId.get(id)?.status) === "superseded" &&
        !/supersed|histor/i.test(l)
      )
        errors.push(
          `${d.replace(ROOT + "/", "")}: cites ${id} (Superseded) as current`,
        );
    }
  }
}

const lines = [
  "# Architecture decision records (ADRs)",
  "",
  "> Generated by `node scripts/sdd/adr-index.mjs`. Do not edit by hand. Template: [0000-template.md](0000-template.md). Pending: [pending.md](pending.md).",
  "> **Inferred** = a description of what the code shows; it does not prove that a formal decision was made. An accepted ADR is immutable: if you change your mind, create a new one that supersedes it.",
  "",
  "| ADR | Decision | Status | Relation |",
  "|---|---|---|---|",
  ...adrs.map(
    (a) =>
      `| [${a.id}](${a.file.split(/[\\/]/).pop()}) | ${a.title} | ${a.status} | ${a.supersededBy ? "superseded by " + a.supersededBy : a.supersedes ? "supersedes " + a.supersedes : ""} |`,
  ),
  "",
];
const next = lines.join("\n");
const target = join(ADR_DIR, "README.md");
if (process.argv.includes("--check")) {
  if (!existsSync(target) || read(target) !== next)
    errors.push(
      "docs/architecture/adr/README.md is out of date: run `node scripts/sdd/adr-index.mjs`",
    );
} else writeFileSync(target, next);

report("adr-index", errors);
